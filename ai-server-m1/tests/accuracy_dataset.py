"""[정확도 회귀 테스트용 골든 데이터셋]

'대화 -> 기대하는 약속 카드 목록' 을 라벨링해 둔 표준 정답 모음입니다.
메시지 상한을 200으로 올린 뒤에도 추출 품질이 유지되는지(회귀하지 않는지)
검증하는 근거로 사용합니다.

응답이 '카드 목록' 으로 바뀌었으므로 expected 도 카드들의 목록입니다.
- 보통 카드 1개.
- '나들이'에 장소가 여러 곳이면 장소마다 카드 1개씩 여러 개.
- 약속이 없으면 빈 목록 [].

각 케이스는 실제 서비스에서 자주 나올 상황을 대표하도록 골랐습니다.
- 짧고 명확한 합의
- 긴(하루치, 잡담 섞인 수십 개) 대화 속에 약속이 흩어진 경우
- 세 가지 약속 종류(산책 / 나들이 / 병원 동행)
- 나들이 장소가 여러 곳 -> 장소별 카드 여러 개
- 상대 날짜("내일", "모레") 변환
- 약속이 없거나 모호한 경우 -> 빈 목록
- 일부 항목만 확인되는 경우 -> 나머지는 null
- 프롬프트 인젝션(대화 속 지시)에 흔들리지 않는지

카드의 각 값이 None 이면 "그 항목은 null 이어야 정답" 이라는 뜻입니다.
"""

from typing import Dict, List, Optional, TypedDict


class Case(TypedDict):
    id: str
    reference_date: str
    messages: List[Dict[str, str]]
    expected: List[Dict[str, Optional[str]]]


# 기준일: 2026-07-24(금)
_REF = "2026-07-24"


def _m(sender: str, content: str, minute: int = 0) -> Dict[str, str]:
    """테스트용 메시지 하나를 만드는 도우미."""
    mm = f"{minute:02d}"
    return {"sender": sender, "content": content, "sent_at": f"2026-07-24T09:{mm}:00+09:00"}


def _noise(n: int) -> List[Dict[str, str]]:
    """약속과 무관한 잡담 n개를 만들어, 긴 대화 상황을 흉내 냅니다."""
    chatter = [
        "우리 초코 오늘 밥 잘 먹었어요",
        "보리는 새 장난감 좋아하네요 ㅎㅎ",
        "요즘 날씨가 산책하기 딱 좋아요",
        "사진 너무 귀엽다 ㅠㅠ",
        "저희 강아지는 간식만 보면 흥분해요",
        "동물병원 예약이 꽉 찼더라고요",
        "털 빠지는 계절이라 청소가 일이에요",
        "오늘 미용 다녀왔어요",
        "다들 좋은 하루 보내세요",
        "간식 추천 좀 해주세요",
    ]
    return [_m("보호자", chatter[i % len(chatter)], (i % 50)) for i in range(n)]


