def build_user_prompt_place_intent(
    conversation_text: str,
    target_label: str,
) -> str:
    """AI 에게 실제로 물어볼 질문을 만듭니다.

    '판단 대상 이름표' + '대화 내용' 을 넣어 하나의 질문 글로 만듭니다.

    판단 대상을 따로 적어주는 이유: 4명 방에서는 최근 3줄이 서로 다른 사람의 말일 수
    있습니다. P1 이 "어제 병원 다녀왔어요" 라고 한 뒤 P3 가 "저도요" 라고 했다면,
    누구를 기준으로 판단하느냐에 따라 답이 달라집니다. 팝업을 받을 사람은 키워드를
    말한 사람이므로, 그 사람을 명시합니다.

    기준일(오늘 날짜)은 넣지 않습니다. 날짜를 계산할 일이 없고,
    좌표와 마찬가지로 필요 없는 정보는 외부 모델로 보내지 않습니다.
    """

    return (
        f"판단 대상: {target_label}\n\n"
        f"다음 대화에서 {target_label} 이(가) 지금 지원 대상 시설을 찾고 있는지 "
        "판단해서, 해당 SHOW_<카테고리> 또는 SUPPRESS 중 한 단어만 출력하세요.\n"
        "----- 대화 시작 -----\n"
        f"{conversation_text}\n"
        "----- 대화 끝 -----"
    )


__all__ = [
    "SYSTEM_PROMPT_PLACE_INTENT",
    "build_user_prompt_place_intent",
]
